#!/usr/bin/env python3
"""Write MatMul9x11x11/Data.lean (the scheme) and MatMul9x11x11/Chunks.lean (the kernel checks)
from the scheme file 9x11x11_708_tensor.mpl (Quantavane, 11 November 2026), which is in the
Maple layout of the Lille catalogue of fast matrix multiplication schemes:

    A . B = sum_i Trace(P_i^T A) * Trace(Q_i^T B) * R_i^T

with P_i of size 9 x 11, Q_i of size 11 x 11 and R_i of size 11 x 9, rational entries.

Each factor is scaled to integers by the least common multiple of the denominators of all its
entries (dU, dV, dW), and every term is written as three sparse lists of (position, integer):
u_i[a][b] = dU P_i[a][b] at position a * 11 + b, v_i[c][d] = dV Q_i[c][d] at position c * 11 + d,
w_i[e][f] = dW R_i[f][e] (the transpose) at position e * 11 + f.

Before writing anything the script checks, in exact integer arithmetic and independently of the
Lean code, that sum_i u_i[a][b] v_i[c][d] w_i[e][f] = dU dV dW [b = c][a = e][d = f] for all
indices. Nothing here is trusted by the Lean proof, which checks the data itself.

Usage: make_data.py SCHEME.mpl OUTDIR
"""
import hashlib, math, re, sys
from collections import defaultdict
from fractions import Fraction

SCHEME_SHA256 = 'ccce4b416505a7af69338709bb4a332f2c87875009e9ff27cce600e97c228d74'
N, M, P, RANK = 9, 11, 11, 708
NS = 'MatMul9x11x11'
SLOT = 40          # bits per slot of the packed integers in the kernel check


def parse(raw):
    line = [l for l in raw.split('\n') if l.startswith('Tensor:=')]
    assert len(line) == 1
    mats = re.findall(r'Matrix\((\d+), ?(\d+), ?\[\[(.*?)\]\]\)', line[0])
    assert len(mats) == 3 * RANK, len(mats)
    out = []
    for i in range(RANK):
        trip = []
        for j, (r, c) in enumerate([(N, M), (M, P), (P, N)]):
            rr, cc, body = mats[3 * i + j]
            assert (int(rr), int(cc)) == (r, c)
            rows = [[Fraction(x) for x in row.split(',')] for row in body.split('],[')]
            assert len(rows) == r and all(len(x) == c for x in rows)
            trip.append(rows)
        out.append(trip)
    return out


def lcm_den(mats):
    d = 1
    for mat in mats:
        for row in mat:
            for x in row:
                d = d * x.denominator // math.gcd(d, x.denominator)
    return d


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    raw = open(src, 'rb').read()
    assert hashlib.sha256(raw).hexdigest() == SCHEME_SHA256, 'unexpected scheme file'
    trip = parse(raw.decode())
    dU = lcm_den(t[0] for t in trip)
    dV = lcm_den(t[1] for t in trip)
    dW = lcm_den(t[2] for t in trip)
    terms = []
    for Pm, Qm, Rm in trip:
        u = [(a * M + b, int(Pm[a][b] * dU)) for a in range(N) for b in range(M) if Pm[a][b] != 0]
        v = [(c * P + d, int(Qm[c][d] * dV)) for c in range(M) for d in range(P) if Qm[c][d] != 0]
        w = [(e * P + f, int(Rm[f][e] * dW)) for e in range(N) for f in range(P) if Rm[f][e] != 0]
        terms.append((u, v, w))
    # independent exact check of every coefficient equation (sparse accumulation over the integers)
    D = dU * dV * dW
    T = defaultdict(int)
    for u, v, w in terms:
        for x, cu in u:
            for y, cv in v:
                cuv = cu * cv
                for z, cw in w:
                    T[(x, y, z)] += cuv * cw
    for a in range(N):
        for b in range(M):
            for d in range(P):
                key = (a * M + b, b * P + d, a * P + d)
                T[key] -= D
    bad = sum(1 for val in T.values() if val != 0)
    assert bad == 0, f'{bad} coefficient equations fail'
    l1 = lambda l: sum(abs(c) for _, c in l)
    bound = sum(l1(u) * l1(v) * l1(w) for u, v, w in terms)
    assert bound + D < 2 ** SLOT, 'slot too small'
    nnz = [sum(len(t[j]) for t in terms) for j in range(3)]
    print(f'scheme ok: rank {RANK}, dU dV dW = {dU} {dV} {dW}, nonzeros {nnz}, '
          f'bound {bound} + D < 2^{SLOT}')

    def lst(l):
        pos = '[' + ', '.join(f'({k}, {c})' for k, c in l if c > 0) + ']'
        neg = '[' + ', '.join(f'({k}, {-c})' for k, c in l if c < 0) + ']'
        return pos + ' ' + neg
    with open(f'{outdir}/{NS}/Data.lean', 'w') as f:
        f.write('module\n\npublic import ' + NS + '.Check\n\n@[expose] public section\n\n')
        f.write('/-!\n# The scheme\n\n')
        f.write('Generated by `scripts/make_data.py` from the scheme file `9x11x11_708_tensor.mpl`\n')
        f.write(f'(SHA-256 `{SCHEME_SHA256}`), in the Maple layout of the\n')
        f.write('Lille catalogue: `A · B = ∑ᵢ Trace(Pᵢᵀ A) Trace(Qᵢᵀ B) Rᵢᵀ`. Each factor is scaled to integers\n')
        f.write('by the least common multiple of its denominators (`dU`, `dV`, `dW`). Term `i` lists the nonzero\n')
        f.write('entries of `dU Pᵢ` at positions `a * 11 + b`, of `dV Qᵢ` at positions `c * 11 + d` and of\n')
        f.write('`dW Rᵢᵀ` at positions `e * 11 + f`, each factor as two lists of pairs (position, absolute value):\n')
        f.write('first the positive entries, then the negative ones. This is data; the proof checks it.\n-/\n\n')
        f.write(f'namespace {NS}\n\n')
        f.write(f'/-- The common denominator of the first factors. -/\ndef dU : Nat := {dU}\n\n')
        f.write(f'/-- The common denominator of the second factors. -/\ndef dV : Nat := {dV}\n\n')
        f.write(f'/-- The common denominator of the third factors. -/\ndef dW : Nat := {dW}\n\n')
        f.write(f'/-- The {RANK} terms of the scheme, scaled to integers. -/\n')
        f.write('noncomputable def terms : List Term := [\n')
        f.write(',\n'.join(f'Term.mk {lst(u)}\n {lst(v)}\n {lst(w)}' for u, v, w in terms))
        f.write(']\n\nend ' + NS + '\n')
    with open(f'{outdir}/{NS}/Chunks.lean', 'w') as f:
        f.write('module\n\npublic import ' + NS + '.Data\n\n@[expose] public section\n\n')
        f.write('/-!\n# The kernel checks\n\n')
        f.write(f'One check per entry `x = a * 11 + b` of the first factor ({N * M} in all), generated by\n')
        f.write('`scripts/make_data.py`. Each is a separate kernel computation (`decide +kernel`), so the\n')
        f.write("kernel's memory is released between them. `slices_ok` collects them.\n-/\n\n")
        f.write(f'namespace {NS}\n\n')
        for x in range(N * M):
            f.write(f'theorem chunk_{x} : sliceOk {M} {P} {SLOT} (dU * dV * dW) terms {x} = true := by\n'
                    '  decide +kernel\n\n')
        f.write(f'/-- Every slice check holds. -/\n')
        f.write(f'theorem slices_ok : ∀ x, x < {N * M} → sliceOk {M} {P} {SLOT} (dU * dV * dW) terms x = true\n')
        for x in range(N * M):
            f.write(f'  | {x}, _ => chunk_{x}\n')
        f.write(f'  | _ + {N * M}, h => absurd h (by omega)\n\n')
        f.write('end ' + NS + '\n')


if __name__ == '__main__':
    main()
